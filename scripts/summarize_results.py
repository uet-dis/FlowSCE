#!/usr/bin/env python3
"""
Compact Markdown summary of the main results (results/SUMMARY.md), read from the result files.

    python scripts/summarize_results.py
"""
import glob, json, os
import numpy as np, pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT); OUT = "results"
NAME = {"cic": "CIC-IDS2018", "doh": "DoHBrw-2020", "unsw": "UNSW-NB15"}; DS = ["cic", "doh", "unsw"]
def md(df):
    return "\n".join(["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)] +
                     ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)])
f = lambda x, d=3: "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"
L = ["# Results summary\n", "Generated by `scripts/summarize_results.py` from the files in `results/`.\n"]

d = pd.DataFrame(json.load(open(f"{OUT}/detector_metrics.json")))
g = d.groupby(["dataset", "kind"]).macro_f1.agg(["mean", "std"]).reset_index()
L += ["## Detectors (macro-F1, five seeds)\n", md(pd.DataFrame([[NAME[r.dataset], r.kind, f"{r['mean']:.4f} ± {r['std']:.4f}"] for _, r in g.iterrows()],
                                                              columns=["Dataset", "Detector", "Macro-F1"])), ""]
rq1 = json.load(open(f"{OUT}/reconstruction_gradient_checks.json"))
L += ["## RQ1: reconstruction and gradient checks on the test graphs\n",
      md(pd.DataFrame([[NAME[k], f"{v['rebuild_max_abs']:.1e}", f"{v['fd_max_abs']:.1e}", f"{v['ctx_share_median']:.1e}"] for k, v in rq1.items()],
                      columns=["Dataset", "Rebuild max |Δ|", "Gradient vs FD max |Δ|", "Context share (median)"])), ""]
E = pd.read_parquet(f"{OUT}/counterfactual_queries.parquet"); rows = []
_pl = sorted(glob.glob(f"{OUT}/ledger/PLUS_*.parquet"))
if _pl: E = pd.concat([E, pd.concat([pd.read_parquet(x) for x in _pl], ignore_index=True).assign(variant="FlowSCE")], ignore_index=True)
for ds in DS:
    for v in ["A0", "A", "B", "C", "D", "FlowSCE"]:
        e = E[(E.dataset == ds) & (E.variant == v)]; s = e[e.v == 1]
        if e.empty: continue
        rows.append([NAME[ds], v, f(e.v.mean()), f"{int(((e.n == 1) & (e.v == 0)).sum())}/{int(e.n.sum())}", f(s.support_eps.median(), 0), f(s.l1.median(), 2), f(s.margin_logit.median())])
L += ["## Ablation on the registered alerts (500 per dataset)\n", md(pd.DataFrame(rows, columns=["Dataset", "Variant", "CSR", "Spurious / nominal", "s_ε", "L1", "Margin"])), ""]
if os.path.exists(f"{OUT}/coupling_sweep_time_queries.parquet"):
    X = pd.read_parquet(f"{OUT}/coupling_sweep_time_queries.parquet"); rows = []
    for (ds, W), q in X.groupby(["dataset", "W"], sort=False):
        a, b, c = (q[q.variant == v] for v in "ABC")
        rows.append([NAME[ds], f"{W:g}", f(q.g_omega_median.median()), f(a.v.mean()), f(c.v.mean()), f"{int(((b.n == 1) & (b.v == 0)).sum())}/{int(b.n.sum())}"])
    T = pd.DataFrame(rows, columns=["Dataset", "Δt (s)", "ω (median)", "CSR A", "CSR C", "Spurious B"])
    L += ["## Time-window coupling sweep (tumbling windows of Δt seconds, five seeds, 100 alerts each)\n", md(T), ""]
def comp(path, keys, title):
    if not os.path.exists(path): return []
    p = pd.read_csv(path); p = p.assign(_d=p.dataset.map({d: i for i, d in enumerate(DS)})).sort_values(["_d"] + keys, kind="stable")
    calls = "oracle_calls_median" if "oracle_calls_median" in p else "n_fwd_median"
    return [f"## {title}\n", md(pd.DataFrame([[NAME.get(r.dataset, r.dataset)] + [getattr(r, k) for k in keys] +
                                             [f(r.CSR), f(r.support_eps_mean, 2), f(r.l1_median, 2), f(r.knn_benign_median, 2), f(r.margin_logit_median), f(getattr(r, calls), 0)]
                                             for r in p.itertuples()], columns=["Dataset"] + keys + ["CSR", "mean s_ε", "L1", "kNN", "Margin", "N_f"])), ""]
L += comp(f"{OUT}/generator_comparison.csv", ["method"], "Generators on the registered alerts (one counterfactual per alert)")
L += comp(f"{OUT}/minimizer_comparison.csv", ["generator", "method"], "Minimizers on the seeds of each generator (shared oracle)")
open(f"{OUT}/SUMMARY.md", "w").write("\n".join(L) + "\n"); print("wrote results/SUMMARY.md")
